def high_half(codec, windows):
    out = []
    for b in range(0x80, 0x100):
        try:
            text = bytes([b]).decode(codec)
            assert len(text) == 1, (codec, b, text)
            out.append(ord(text))
        except UnicodeDecodeError:
            out.append(b if windows and b < 0xA0 else 0xFFFD)
    return out


def main():
    print("// @generated by tools/gen_tables.py. Do not edit by hand.")
    print("//")
    print("// Upper halves (bytes 0x80..=0xFF) of the supported single-byte code pages.")
    print("// Bytes 0x00..=0x7F are ASCII in every one of them.")
    print()
    print("pub(crate) struct Page {")
    print("    pub name: &'static str,")
    print("    pub labels: &'static [&'static str],")
    print("    /// The Windows code page number, or 0 when there is none.")
    print("    pub code_page: u32,")
    print("    pub high: [u16; 128],")
    print("}")
    print()
    print(f"pub(crate) static PAGES: [Page; {len(PAGES)}] = [")
    for name, codec, cp, labels in PAGES:
        for b in range(0x80):
            assert bytes([b]).decode(codec) == chr(b), (codec, b)
        windows = name.startswith("windows-")
        high = high_half(codec, windows)
        code_page = 0 if cp == 874_11 else cp
        print("    Page {")
        print(f"        name: {name!r},".replace("'", '"'))
        print("        labels: &[" + ", ".join(f'"{l}"' for l in labels) + "],")
        print(f"        code_page: {code_page},")
        print("        high: [")
        for row in range(0, 128, 8):
            print("            " + " ".join(f"0x{c:04X}," for c in high[row:row + 8]))
        print("        ],")
        print("    },")
    print("];")


if __name__ == "__main__":
    main()
